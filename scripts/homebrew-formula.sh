#!/usr/bin/env bash
# Prints the Homebrew formula for a release from its SHA256SUMS.
#   scripts/homebrew-formula.sh 0.6.0 dist/SHA256SUMS > dvarapala.rb
# franzramadhan/homebrew-tap runs it for each new release.
set -euo pipefail
version=$1
sums=$2
base="https://github.com/franzramadhan/dvarapala/releases/download/v${version}"

sha() {
  local file="dvarapala-v${version}-$1.tar.gz"
  local s
  s=$(awk -v f="$file" '$2 == f {print $1}' "$sums")
  [ -n "$s" ] || { echo "no checksum for $file in $sums" >&2; exit 1; }
  printf '%s' "$s"
}

# all four first: a failure inside the heredoc below would not stop the script
mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-musl)
linux_intel=$(sha x86_64-unknown-linux-musl)

cat <<RUBY
# Generated by scripts/homebrew-formula.sh in franzramadhan/dvarapala: do not edit.
class Dvarapala < Formula
  desc "Anti-DDoS gateway with L4 to L7 protection"
  homepage "https://dvarapala.franzramadhan.dev"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/dvarapala-v${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/dvarapala-v${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/dvarapala-v${version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/dvarapala-v${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${linux_intel}"
    end
  end

  def install
    bin.install "dvarapala"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/dvarapala --version")
  end
end
RUBY
