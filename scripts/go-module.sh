#!/bin/sh
# RFC 0027: write the github.com/franzramadhan/dvarapala-go module tree.
#
#   scripts/go-module.sh <out dir> <lib dir>
#
# <lib dir> holds <goos>_<goarch>/libdvarapala.a, stripped, for the
# platforms to ship. The Go files come from sdk/go, except link.go,
# which points at the prebuilt libraries here instead of a checkout.
set -eu
out=$1 libs=$2
root=$(cd "$(dirname "$0")/.." && pwd)
module=github.com/franzramadhan/dvarapala-go

mkdir -p "$out/include"
for f in "$root"/sdk/go/*.go; do
  [ "$(basename "$f")" = link.go ] || cp "$f" "$out/"
done
cp "$root/crates/ffi/dvarapala.h" "$out/include/"
cp "$root/LICENSE" "$out/"
for d in "$libs"/*_*/; do
  p=$(basename "$d")
  mkdir -p "$out/lib/$p"
  cp "$d/libdvarapala.a" "$out/lib/$p/"
done

{
  echo "module $module"
  echo
  grep '^go ' "$root/sdk/go/go.mod"
} > "$out/go.mod"

{
  cat <<'GO'
//go:build cgo && (linux || darwin) && (amd64 || arm64)

package dvarapala

// Generated by scripts/go-module.sh in franzramadhan/dvarapala: the
// prebuilt static library per platform (RFC 0027).

/*
#cgo CFLAGS: -I${SRCDIR}/include
GO
  for p in linux_amd64 linux_arm64 darwin_amd64 darwin_arm64; do
    echo "#cgo ${p%_*},${p#*_} LDFLAGS: \${SRCDIR}/lib/$p/libdvarapala.a"
  done
  cat <<'GO'
#cgo LDFLAGS: -lm
#cgo linux LDFLAGS: -ldl -lpthread
*/
import "C"
GO
} > "$out/link.go"

cat > "$out/README.md" <<EOF2
# dvarapala-go

The Go SDK of [dvarapala](https://github.com/franzramadhan/dvarapala):
the gateway's rate limit, flood detection, connection limits, routes and
egress shaping, in process. Generated from \`sdk/go\` by each release,
with the static library prebuilt for linux and darwin on amd64 and arm64.
Needs cgo and a C toolchain, no Rust.

\`\`\`sh
go get $module
\`\`\`

Docs: https://dvarapala.franzramadhan.dev/docs/sdk.html. Issues and pull
requests go to [franzramadhan/dvarapala](https://github.com/franzramadhan/dvarapala).
EOF2
